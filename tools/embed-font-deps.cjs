'use strict';
// Offline, hash-pinned build. Never downloads executable dependencies.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const lock = JSON.parse(fs.readFileSync(path.join(root, 'vendor/font-deps.lock.json'), 'utf8'));
const bytes = fs.readFileSync(path.join(root, 'vendor/font-deps.js'));
if (crypto.createHash('sha256').update(bytes).digest('hex') !== lock.sha256) throw new Error('字体依赖 SHA-256 与锁文件不符');
const source = bytes.toString('utf8').replace(/\r\n/g, '\n');
const table = JSON.parse(source.match(/var CX_EMBEDDED_FONT_TABLE=(.*);/)[1]);
const entries = Object.entries(table).filter(([key]) => !['author', 'namespace', 'license', 'version'].includes(key));
if (entries.length !== lock.fingerprints || table.version !== lock.fontTableVersion || entries.some(([key, cp]) => !/^[a-f0-9]{8}$/i.test(key) || !Number.isInteger(cp) || cp < 0x4e00 || cp > 0x9fa5)) throw new Error('字体映射结构无效');
const start = '  /*__CX_LOCAL_FONT_DEPS_START__*/';
const end = '  /*__CX_LOCAL_FONT_DEPS_END__*/';
const block = [start, '  // Generated by tools/embed-font-deps.cjs; see vendor/NOTICE.md.',
  '  let localFontDepsCache = null;',
  '  function loadLocalFontDeps() {',
  '    if (localFontDepsCache) return localFontDepsCache;',
  '    const scope = {};',
  '    localFontDepsCache = (function (module, define) {', source.trimEnd(),
  '      return { Typr, md5: this.md5, table: CX_EMBEDDED_FONT_TABLE };',
  '    }).call(scope);',
  '    return localFontDepsCache;',
  '  }', end].join('\n');
const context = vm.createContext({});
vm.runInContext(block + '\nthis.deps = loadLocalFontDeps();', context);
if (context.deps.md5('abc') !== '900150983cd24fb0d6963f7d28e17f72' || typeof context.deps.Typr.U.glyphToPath !== 'function') throw new Error('字体组件自检失败');
const target = path.join(root, '学习通刷课助手.user.js');
const script = fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
const from = script.indexOf(start), to = script.indexOf(end);
if (from < 0 || to < from || script.indexOf(start, from + start.length) !== -1 || script.indexOf(end, to + end.length) !== -1) throw new Error('字体组件标记缺失或重复');
const output = script.slice(0, from) + block + script.slice(to + end.length);
new vm.Script(output);
if (process.argv.includes('--check')) {
  if (output !== script) throw new Error('内置字体组件与锁定资源不一致,请先执行 npm run build:fonts');
  console.log('字体组件一致性检查通过: ' + entries.length + ' 条指纹');
} else {
  if (output !== script) fs.writeFileSync(target, output, 'utf8');
  console.log('已内置锁定字体组件: ' + entries.length + ' 条指纹');
}
